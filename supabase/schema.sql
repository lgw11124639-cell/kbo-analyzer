-- 테스트 계정 최초 5,000⚾ 지급
-- reference_key UNIQUE 조건으로 이 SQL을 다시 실행해도 중복 지급되지 않는다.
do $$
declare
  target_user uuid := 'b07e1249-c197-4d0c-9e77-ba310c6147bc';
  grant_amount bigint := 5000;
  new_balance bigint;
begin
  insert into public.kbo_baseball_wallets (user_id)
  values (target_user)
  on conflict (user_id) do nothing;

  if not exists (
    select 1
    from public.kbo_baseball_ledger
    where user_id = target_user
      and reference_key = 'TEST_GRANT_5000_V1'
  ) then
    update public.kbo_baseball_wallets
    set balance = balance + grant_amount,
        lifetime_earned = lifetime_earned + grant_amount,
        updated_at = now()
    where user_id = target_user
    returning balance into new_balance;

    insert into public.kbo_baseball_ledger (
      user_id,
      amount,
      balance_after,
      transaction_type,
      reference_key,
      description
    ) values (
      target_user,
      grant_amount,
      new_balance,
      'TEST_GRANT',
      'TEST_GRANT_5000_V1',
      '테스트 계정 최초 야구공 지급'
    );
  end if;
end $$;

